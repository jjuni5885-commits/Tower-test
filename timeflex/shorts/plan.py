# 쇼츠 구성표: 박자(140bpm)에 맞춘 장면 경계, 자막, 연출
FPS = 30
BPM = 140
BEAT = 60.0 / BPM


def F(b):
    return int(round(b * BEAT * FPS))


Y = '#FFD84A'   # 노란 강조
W = '#FFFFFF'

# 장면: (이름, 캡처 시작 프레임, 박자 수, 자막 목록)
# 자막: (장면 안 시작 프레임, 끝 프레임(None=끝까지), 작은 꼬리표, 큰 글 줄 목록[[(글, 색), ...], ...])
SCENES = [
    ('hook', 0, 10, [
        (0, 'H1', '시간이 뒤섞인 타워 디펜스', [[('거북선', Y), ('이 탑이 된다고?', W)]]),
        ('H1', None, '시간이 뒤섞인 타워 디펜스', [[('원시 시대부터', W)], [('우주 전쟁', Y), ('까지', W)]]),
    ]),
    ('m1', 0, 6, [(0, None, '기원전 1만 년', [[('거대 매머드 왕', W)]])]),
    ('m2', 0, 6, [(0, None, '로마 제국', [[('폭군 황제', W), ('의 군단', W)]])]),
    ('m3', 0, 6, [(0, None, '바이킹 시대', [[('서리 거인 왕', W)]])]),
    ('m4', 0, 6, [(0, None, '대항해 시대', [[('크라켄', Y), (' 출현', W)]])]),
    ('m5', 0, 6, [(0, None, '1차 세계대전', [[('육상 전함', W), (' 돌격', W)]])]),
    ('m6', 0, 6, [(0, None, '2차 세계대전', [[('상륙 작전', W)]])]),
    ('m7', 0, 6, [(0, None, '근미래', [[('네온 도시', Y), (' 방어전', W)]])]),
    ('m8', 0, 6, [(0, None, '우주 시대', [[('외계 모선', W), (' 침공', W)]])]),
    ('boss', 13, 12, [
        (0, 'K', '시대마다 등장하는 우두머리', [[('보스 잡는 맛', W)]]),
        ('K+10', None, '15개 시대, 105개 전장', [[('끝까지 ', W), ('막아 낼 수', Y)], [('있을까?', W)]], 1180),
    ]),
    ('end', 0, 8, []),
]
BOSS_DEATH = 77   # boss 장면 안 프레임(캡처 90 - 시작 13)


def timeline():
    out, b = [], 0
    for name, s0, nb, caps in SCENES:
        f0, f1 = F(b), F(b + nb)
        out.append(dict(name=name, s0=s0, beats=nb, b0=b, f0=f0, n=f1 - f0, caps=caps))
        b += nb
    return out


if __name__ == '__main__':
    T = timeline()
    for t in T:
        print(t['name'], t['b0'], t['f0'], t['n'])
    print('total frames', T[-1]['f0'] + T[-1]['n'], 'sec', (T[-1]['f0'] + T[-1]['n']) / FPS)
