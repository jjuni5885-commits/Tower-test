// ===== tf_audio.js : 타임플렉스 시대 음악 (합성음으로 시대 분위기를 흉내) =====
// 곡 이름: battle_<장 분위기>, boss_<장 분위기>. audio2.js sn2Song이 장의 mood로 찾고, 없으면 기본 전투곡
// 원시(prim): A 단조 5음계(라 도 레 미 솔), 통나무 북(tom), 큰북(buk), 나무 딱딱이, 뼈피리(fife), 낮은 드론(bass), 뒤 절에 합창 같은 패드
(function () {
  var PEN = [57, 60, 62, 64, 67, 69, 72, 74, 76];   // A3 C4 D4 E4 G4 A4 C5 D5 E5
  // 가락 8마디(두 번 돌며 뒤 절은 한 옥타브 위와 겹침): [박, 길이, 5음계 번호]
  var MEL = [
    [[0, 1, 5], [1, 0.5, 4], [1.5, 0.5, 3], [2, 2, 2]], [[0, 1, 3], [1, 1, 4], [2, 1.5, 5], [3.5, 0.5, 4]],
    [[0, 1, 5], [1, 0.5, 6], [1.5, 0.5, 5], [2, 1, 4], [3, 1, 3]], [[0, 3, 2], [3, 0.5, 3], [3.5, 0.5, 4]],
    [[0, 1.5, 5], [1.5, 0.5, 6], [2, 2, 7]], [[0, 1, 6], [1, 1, 5], [2, 1, 4], [3, 1, 3]],
    [[0, 1, 2], [1, 0.5, 3], [1.5, 0.5, 2], [2, 1, 1], [3, 1, 2]], [[0, 3.5, 0]]];
  var PROG = [[33, 57, 64, 69], [36, 60, 64, 67], [38, 57, 62, 69], [33, 57, 64, 69], [31, 55, 62, 67], [36, 60, 64, 67], [38, 57, 62, 65], [33, 57, 64, 69]];
  SONGS.battle_prim = { bpm: 104, bars: 16, vol: 1.0, wet: 0.3, prog: PROG.concat(PROG), mel: MEL.concat(MEL),
    build: function (S) {
      for (var b = 0; b < S.bars; b++) {
        var t0 = b * 4, P = S.prog[b], sec = b >= 8, r = P[0], k;
        // 드론: 으뜸음과 5도가 길게 (낮은 동굴 울림)
        S.n('bass', t0, 3.8, r, 0.75); if (b % 2 === 0) S.n('bass', t0 + 2, 1.8, r + 7, 0.4);
        // 통나무 북: 쿵 . 쿵쿵 . 쿵 . 쿵 (셋째 박 당김)
        [[0, 45, 1], [1, 50, 0.55], [1.5, 50, 0.5], [2.5, 45, 0.8], [3, 52, 0.55], [3.5, 50, 0.45]].forEach(function (h) { S.n('tom', t0 + h[0], 0.2, h[1], h[2]); });
        S.d('buk', t0, sec ? 0.9 : 0.7); if (sec) S.d('buk', t0 + 2.5, 0.6);
        for (k = 0; k < 8; k++) S.d('shk', t0 + k * 0.5, k % 2 ? 0.55 : 0.3);
        S.n('wood', t0 + 1, 0.1, 76, 0.45); S.n('wood', t0 + 3, 0.1, 72, 0.45); if (sec) S.n('wood', t0 + 3.5, 0.1, 79, 0.35);
        // 뼈피리 가락 (뒤 절은 위 옥타브 겹침)
        S.mel[b].forEach(function (x) { var m = PEN[x[2]]; S.n('fife', t0 + x[0], x[1], m + 12, 1.1); if (sec) S.n('fife', t0 + x[0], x[1], m + 24, 0.5); });
        // 뒤 절: 합창 같은 패드와 큰 북
        if (sec) { for (k = 1; k < 4; k++) S.n('pad', t0, 3.8, P[k] - 12, 0.32); S.n('timp', t0, 0.5, r + 12, 0.6); }
        if (b % 8 === 7) [[2, 52], [2.25, 52], [2.5, 50], [2.75, 50], [3, 47], [3.25, 45], [3.5, 45], [3.75, 43]].forEach(function (x, q) { S.n('tom', t0 + x[0], 0.2, x[1], 0.5 + q * 0.06); });
      }
    } };
  // 우두머리(매머드 왕): 더 빠르고 무겁게. 팀파니 두 대가 번갈아, 뼈피리는 높게 외침
  SONGS.boss_prim = { bpm: 128, bars: 16, vol: 0.92, wet: 0.24, prog: PROG.concat(PROG), mel: MEL.concat(MEL),
    build: function (S) {
      for (var b = 0; b < S.bars; b++) {
        var t0 = b * 4, P = S.prog[b], r = P[0] - 2, sec = b >= 8, k;
        [r, r, r + 12, r, r + 7, r, r + 10, r + 7].forEach(function (m, q) { S.n('bass', t0 + q * 0.5, 0.45, m, q % 2 ? 0.5 : 0.85); });
        for (k = 0; k < 4; k++) { S.d('kick', t0 + k, k % 2 ? 0.7 : 1); S.n('timp', t0 + k + 0.5, 0.4, k % 2 ? r + 19 : r + 12, 0.55); }
        S.d('buk', t0, 1); S.d('buk', t0 + 2, 0.8);
        [[0.75, 50], [1.75, 52], [2.75, 50], [3.25, 55], [3.75, 52]].forEach(function (h) { S.n('tom', t0 + h[0], 0.15, h[1], 0.55); });
        for (k = 0; k < 8; k++) S.d('shk', t0 + k * 0.5, k % 2 ? 0.6 : 0.35);
        S.mel[b].forEach(function (x) { var m = PEN[x[2]] - 2 + 12; S.n('fife', t0 + x[0], x[1], m, 1.15); if (sec) S.n('str', t0 + x[0], x[1], m - 12, 0.6); });
        if (sec) for (k = 1; k < 4; k++) S.n('pad', t0, 3.8, P[k] - 14, 0.3);
        if (b % 8 === 0) S.d('cym', t0, 0.8);
      }
    } };
})();
